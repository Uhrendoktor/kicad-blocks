#!/usr/bin/env python3
"""Generate or verify the complete Markdown inventory of tests and purposes."""

from __future__ import annotations

import argparse
import ast
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
TEST_ROOT = ROOT / "tests"
INVENTORY = TEST_ROOT / "TEST_INVENTORY.md"

# These executable integration/evidence runners are invoked explicitly by CI;
# they are not pytest test functions and must remain separately inventoried.
RUNNER_PURPOSES = {
    "tests/test_eeschema_gui.py": (
        "Launches the real Eeschema editor under a virtual display, performs the "
        "schematic edit/save workflow, and verifies the resulting native document."
    ),
    "tests/test_instance_configuration_gui.py": (
        "Opens the real instance-configuration dialog and verifies variant, profile, "
        "typed-parameter and PCB-layout values through KiCad IPC."
    ),
    "tests/test_ipc_headless.py": (
        "Exercises real headless schematic IPC for block creation, catalog registration, "
        "instance metadata and placement invariants."
    ),
    "tests/test_library_picker_gui.py": (
        "Renders a real KiCad facade symbol and exercises the native-rendered library picker."
    ),
    "tests/test_pcb_ipc.py": (
        "Exercises KiCad's actual PCB IPC primitives and checks imported board-item identity."
    ),
    "tests/test_pcb_layout.py": (
        "Merges stored PCB layouts into a copied board, then validates exported and reloaded "
        "board geometry, nets, references and project settings."
    ),
    "tests/test_plugin_registration.py": (
        "Installs the plugin into an isolated KiCad profile, verifies the managed Python "
        "environment and action discovery, and exercises the native symbol chooser."
    ),
    "tests/capture_visual_docs.py": (
        "Captures the documented KiCad UI surfaces and emits the source-pinned visual evidence bundle."
    ),
    "tests/validate_kicad_cli.py": (
        "Uses the real KiCad CLI to validate generated schematic, PCB, BOM and recursive ERC artifacts."
    ),
}


def _discover_test_cases(test_root: Path) -> dict[str, list[tuple[str, str]]]:
    """Return every test function and a readable purpose derived from its name."""
    cases: dict[str, list[tuple[str, str]]] = {}
    for path in sorted(test_root.glob("test_*.py")):
        source = path.read_text(encoding="utf-8")
        tree = ast.parse(source, filename=str(path))
        relative = path.relative_to(ROOT).as_posix()
        entries: list[tuple[str, str]] = []

        class Visitor(ast.NodeVisitor):
            """Collect test functions and retain their owning test class."""

            def __init__(self) -> None:
                self.classes: list[str] = []

            def visit_ClassDef(self, node: ast.ClassDef) -> None:
                self.classes.append(node.name)
                for child in node.body:
                    self.visit(child)
                self.classes.pop()

            def visit_FunctionDef(self, node: ast.FunctionDef) -> None:
                if node.name.startswith("test_"):
                    name = ".".join((*self.classes, node.name)) if self.classes else node.name
                    entries.append((name, _purpose_from_name(node.name)))

            def visit_AsyncFunctionDef(self, node: ast.AsyncFunctionDef) -> None:
                if node.name.startswith("test_"):
                    name = ".".join((*self.classes, node.name)) if self.classes else node.name
                    entries.append((name, _purpose_from_name(node.name)))

        Visitor().visit(tree)
        if entries:
            cases[relative] = entries
    return cases


def _purpose_from_name(test_name: str) -> str:
    """Convert the descriptive test identifier into a stable human-readable purpose."""
    phrase = re.sub(r"_+", " ", test_name.removeprefix("test_")).strip()
    phrase = phrase.replace("kicad", "KiCad").replace("ipc", "IPC").replace("gui", "GUI")
    phrase = phrase.replace("pcb", "PCB").replace("bom", "BOM").replace("erc", "ERC")
    phrase = phrase.replace("kiid", "KIID").replace("sha", "SHA")
    phrase = phrase.replace("tls", "TLS").replace("svg", "SVG")
    return f"Checks: {phrase[0].lower() + phrase[1:] if phrase else 'test behavior'}."


def render_inventory(test_root: Path = TEST_ROOT) -> str:
    """Render the complete suite and executable-runner inventory."""
    cases = _discover_test_cases(test_root)
    lines = [
        "# Test inventory",
        "",
        "<!-- Generated by scripts/check_test_inventory.py; do not edit by hand. -->",
        "",
        "Every pytest/unittest test method and every standalone CI acceptance runner is listed below.",
        "The inventory checker fails when a test is added, removed or renamed without updating this file.",
        "",
        "## Test methods",
        "",
    ]
    method_count = 0
    for path, entries in cases.items():
        lines.extend([f"### `{path}`", "", "| Test | Purpose |", "| --- | --- |"])
        for name, purpose in entries:
            lines.append(f"| `{name}` | {purpose} |")
            method_count += 1
        lines.append("")
    lines.extend(
        [
            "## Standalone integration and evidence runners",
            "",
            "These scripts execute real KiCad/GUI/IPC acceptance flows when invoked directly by CI; "
            "pytest import/collection does not execute their `main()` functions.",
            "",
            "| Runner | Purpose |",
            "| --- | --- |",
        ]
    )
    for path, purpose in sorted(RUNNER_PURPOSES.items()):
        if not (ROOT / path).is_file():
            raise FileNotFoundError(f"Inventoried test runner is missing: {path}")
        lines.append(f"| `{path}` | {purpose} |")
    lines.extend(
        [
            "",
            f"**Inventory totals:** {method_count} test methods across {len(cases)} Python modules; "
            f"{len(RUNNER_PURPOSES)} standalone integration/evidence runners.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    """Write the generated inventory or fail when the checked-in copy is stale."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true", help="write the inventory file")
    parser.add_argument("--check", action="store_true", help="verify the checked-in inventory")
    args = parser.parse_args()
    expected = render_inventory()
    if args.write:
        INVENTORY.write_text(expected, encoding="utf-8")
        print(f"test-inventory=written path={INVENTORY.relative_to(ROOT)}")
        return 0
    if not INVENTORY.is_file() or INVENTORY.read_text(encoding="utf-8") != expected:
        print("test-inventory=failed; run python scripts/check_test_inventory.py --write")
        return 1
    print("test-inventory=passed; every discovered test has an inventory entry")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
