"""Generate the maintained UI screen inventory from the interaction catalog."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import NotRequired, TypedDict, cast

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from scripts.visual_asset_inventory import ASSET_NAMES  # noqa: E402

CATALOG_PATH = ROOT / "tests" / "ui_contract_catalog.json"
DEFAULT_OUTPUT = ROOT / "docs" / "ui-inventory.md"
PREVIEW_BASE = (
    "https://raw.githubusercontent.com/Uhrendoktor/kicad-blocks/refs/heads/docs/previews/previews"
)
TICK = chr(96)
COVERAGE_LABELS = {
    "contracted": "Contracted — widget action and expected UI transition asserted",
    "partial": "Partial — targeted GUI, integration, or visual checks exist",
    "inventory-only": "Inventory only — systematic UI contracts not implemented yet",
}
ASSERTION_LABELS = {
    "asserted": "behavior asserted",
    "observed": "result observed",
    "uncovered": "discovered; interaction not yet asserted",
}


class UIControl(TypedDict):
    contract_id: str
    label: str
    assertion: str
    type: NotRequired[str]
    action_id: NotRequired[str]


class UIAction(UIControl):
    action_id: str


class UIView(TypedDict):
    label: str
    actions: NotRequired[list[UIAction]]
    screenshots: NotRequired[list[str]]


class UIScreen(TypedDict):
    id: str
    title: str
    purpose: str
    coverage: str
    coverage_note: str
    evidence: NotRequired[list[str]]
    views: NotRequired[list[UIView]]
    controls: NotRequired[list[UIControl]]
    footer_controls: NotRequired[list[UIControl]]
    screenshots: NotRequired[list[str]]
    functionality: NotRequired[list[str]]


class UICatalog(TypedDict):
    schema_version: int
    source_of_truth: str
    screens: list[UIScreen]


def load_catalog(path: Path = CATALOG_PATH) -> UICatalog:
    """Load the UI catalog into its domain schema and check semantic invariants."""
    catalog = cast(UICatalog, json.loads(path.read_text(encoding="utf-8")))
    if catalog.get("schema_version") != 1:
        raise ValueError("Unsupported UI contract catalog schema_version.")
    screens = catalog.get("screens", [])
    if not screens:
        raise ValueError("The UI contract catalog must contain at least one screen.")

    screen_ids = [screen["id"] for screen in screens]
    if len(screen_ids) != len(set(screen_ids)):
        raise ValueError("UI screen IDs must be unique.")
    unknown_statuses = sorted({screen["coverage"] for screen in screens} - set(COVERAGE_LABELS))
    if unknown_statuses:
        raise ValueError(f"Unknown UI coverage status: {unknown_statuses!r}")

    for screen in screens:
        control_records: list[UIControl] = list(screen.get("controls", []))
        control_records.extend(screen.get("footer_controls", []))
        for view in screen.get("views", []):
            control_records.extend(view.get("actions", []))
        control_ids = [item["contract_id"] for item in control_records]
        if len(control_ids) != len(set(control_ids)):
            raise ValueError(f"Duplicate semantic control ID in screen {screen['id']!r}.")
        invalid_assertions = sorted(
            {
                item.get("assertion")
                for item in control_records
                if item.get("assertion") not in ASSERTION_LABELS
            },
            key=lambda value: "" if value is None else value,
        )
        if invalid_assertions:
            raise ValueError(
                f"Screen {screen['id']!r} has missing or invalid per-control assertion labels: "
                f"{invalid_assertions!r}"
            )

    missing_assets = sorted(referenced_assets(catalog) - ASSET_NAMES)
    if missing_assets:
        raise ValueError(
            "UI catalog references images outside scripts/visual_asset_inventory.py: "
            + ", ".join(missing_assets)
        )
    return catalog


def referenced_assets(catalog: UICatalog) -> set[str]:
    assets: set[str] = set()
    for screen in catalog["screens"]:
        assets.update(screen.get("screenshots", []))
        for view in screen.get("views", []):
            assets.update(view.get("screenshots", []))
    return assets


def _unique_screenshots(screen: UIScreen) -> list[str]:
    values = list(screen.get("screenshots", []))
    for view in screen.get("views", []):
        values.extend(view.get("screenshots", []))
    return list(dict.fromkeys(values))


def render_inventory(catalog: UICatalog) -> str:
    screens = catalog["screens"]
    counts = {
        status: sum(screen["coverage"] == status for screen in screens)
        for status in COVERAGE_LABELS
    }
    lines = [
        "<!-- Generated by scripts/generate_ui_inventory.py; edit tests/ui_contract_catalog.json instead. -->",
        "# UI window and interaction inventory",
        "",
        "This page is generated from the declarative UI catalog. It inventories the current user-facing surfaces, their major workflows, the automated evidence available, and real production screenshots. It does **not** claim that a screenshot or a visible control proves the complete workflow.",
        "",
        "| Coverage status | Screens | Meaning |",
        "|---|---:|---|",
        f"| Contracted | {counts['contracted']} | Widget-level execute/result assertions are registered and run in CI. |",
        f"| Partial | {counts['partial']} | Targeted GUI, integration, model, or screenshot checks exist; the full control matrix is not contracted. |",
        f"| Inventory only | {counts['inventory-only']} | Window/workflow is documented here; systematic interaction contracts remain future work. |",
        "",
        "The first contract milestones cover Task Hub routing and navigation and the Add PCB layout dialog's application-owned controls. The Functional Block Library and implementation manager have substantial partial contract coverage. None of this implies that every downstream KiCad operation or native OS chooser has been proven.",
        "",
        "## Screens",
        "",
    ]

    for screen in screens:
        title = screen["title"]
        lines.extend(
            [
                f"### {title}",
                "",
                screen["purpose"],
                "",
                f"**Coverage:** {COVERAGE_LABELS[screen['coverage']]}.",
                "",
                screen["coverage_note"],
                "",
            ]
        )

        views = screen.get("views", [])
        if views:
            lines.append("**Views and actions**")
            lines.append("")
            for view in views:
                lines.append(f"- **{view['label']}**")
                for action in view.get("actions", []):
                    status = ASSERTION_LABELS[action["assertion"]]
                    lines.append(
                        f"  - {action['label']} ({TICK}{action['contract_id']}{TICK}; {status})"
                    )
        else:
            lines.append("**Major functionality**")
            lines.append("")
            for item in screen.get("functionality", []):
                lines.append(f"- {item}")
        lines.append("")

        controls = screen.get("controls", [])
        if controls:
            lines.append("**Registered semantic controls**")
            lines.append("")
            for control in controls:
                status = ASSERTION_LABELS[control["assertion"]]
                lines.append(
                    f"- {control['label']} ({TICK}{control['contract_id']}{TICK}; {control.get('type', 'control')}; {status})"
                )
            lines.append("")

        footer = screen.get("footer_controls", [])
        if footer:
            lines.append("**Other controls**")
            lines.append("")
            for control in footer:
                status = ASSERTION_LABELS[control["assertion"]]
                lines.append(
                    f"- {control['label']} ({TICK}{control['contract_id']}{TICK}; {status})"
                )
            lines.append("")

        evidence = screen.get("evidence", [])
        if evidence:
            lines.append("**Current automated evidence**")
            lines.append("")
            for entry in evidence:
                lines.append(f"- {TICK}{entry}{TICK}")
            lines.append("")

        screenshots = _unique_screenshots(screen)
        if screenshots:
            lines.append("**Production screenshots**")
            lines.append("")
            for asset in screenshots:
                label = asset.replace("-", " ").replace("_", " ")
                lines.append(f"![{title}: {label}]({PREVIEW_BASE}/{asset})")
                lines.append(f"[Open {asset}]({PREVIEW_BASE}/{asset})")
                lines.append("")
        else:
            lines.extend(
                [
                    "**Production screenshots:** Not yet captured for this surface.",
                    "",
                ]
            )

        lines.append("---")
        lines.append("")

    lines.extend(
        [
            "## Coverage interpretation",
            "",
            "- **Contracted** means the listed UI component's actual Tcl/Tk command was executed and its expected callback or visible state transition was asserted. It is not a substitute for verifying a downstream KiCad operation or a native OS file chooser.",
            "- **Partial** means there are useful targeted checks, but one or more controls, views, failure paths, or side effects are not covered by reusable contracts.",
            "- **Inventory only** means the screen and its major functions are recorded for discovery and rollout planning; do not treat it as tested.",
            "",
            "Per-control status is explicit: **behavior asserted** means a real interaction is executed and checked; **result observed** means a dependent state (such as a selected row's label or a visible pane) is checked; **discovered; interaction not yet asserted** means the control is present but its action still needs an interaction contract.",
            "",
            "For the reusable component model and framework decisions, see [UI testing architecture](explanation/ui-testing-architecture.md).",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument(
        "--check",
        action="store_true",
        help="fail if the committed inventory differs from generated content",
    )
    args = parser.parse_args()

    try:
        rendered = render_inventory(load_catalog())
    except (OSError, ValueError, json.JSONDecodeError) as exc:
        print(f"UI inventory generation failed: {exc}", file=sys.stderr)
        return 1

    if args.check:
        if not args.output.is_file():
            print(f"Generated inventory is missing: {args.output}", file=sys.stderr)
            return 1
        actual = args.output.read_text(encoding="utf-8")
        if actual != rendered:
            print(
                f"{args.output} is stale. Run scripts/generate_ui_inventory.py.",
                file=sys.stderr,
            )
            return 1
        print(f"UI inventory is current: {args.output}")
        return 0

    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(rendered, encoding="utf-8")
    print(f"Generated UI inventory: {args.output}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
