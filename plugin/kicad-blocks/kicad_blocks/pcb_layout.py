class _Quoted(str):
    """Keep quoted S-expression strings distinct from bare atoms."""


def _lex(source: str):
    i = 0
    while i < len(source):
        ch = source[i]
        if ch.isspace():
            i += 1
            continue
        if ch == ";":
            end = source.find("\n", i)
            i = len(source) if end < 0 else end + 1
            continue
        if ch in "()":
            yield ch
            i += 1
            continue
        if ch == '"':
            i += 1
            start = i
            escaped = False
            out = []
            while i < len(source):
                cur = source[i]
                if escaped:
                    out.append("\\" + cur)
                    escaped = False
                elif cur == "\\":
                    escaped = True
                elif cur == '"':
                    break
                else:
                    out.append(cur)
                i += 1
            if i >= len(source):
                raise ValueError("Unterminated quoted string in KiCad S-expression.")
            raw = "".join(out)
            try:
                value = json.loads('"' + raw + '"')
            except json.JSONDecodeError as exc:
                raise ValueError(f"Invalid quoted string in KiCad S-expression: {exc}") from exc
            yield _Quoted(value)
            i += 1
            continue
        start = i
        while i < len(source) and not source[i].isspace() and source[i] not in "()":
            i += 1
        yield source[start:i]


